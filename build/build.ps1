#Requires -Version 7.6

<#
.SYNOPSIS
    Builds the standalone passkey scripts and the Passkey module from explicit source lists.
.DESCRIPTION
    Output is deterministic UTF-8 without a BOM, with LF line endings. -Check compares
    expected files and bytes without writing anything to the repository. Source files
    contain function declarations only; entrypoints retain their own help and parameters.
.PARAMETER Check
    Validate checked-in output, including generated-file inventory, without changing files.
.PARAMETER RepositoryRoot
    Repository directory. Defaults to the parent of this build directory.
#>
[CmdletBinding()]
param(
    [switch]$Check,
    [string]$RepositoryRoot = (Split-Path -Parent $PSScriptRoot)
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$utf8 = [System.Text.UTF8Encoding]::new($false, $true)
$root = [System.IO.Path]::TrimEndingDirectorySeparator([System.IO.Path]::GetFullPath($RepositoryRoot))
$generatedMarker = '# Generated by build/build.ps1.'

function Resolve-RepoPath {
    param([string]$RelativePath)
    if ([string]::IsNullOrWhiteSpace($RelativePath) -or
        [System.IO.Path]::IsPathRooted($RelativePath) -or $RelativePath.Contains('\') -or
        $RelativePath.Split('/') -contains '..' -or $RelativePath.Split('/') -contains '.') {
        throw "Expected a repository-relative forward-slash path: '$RelativePath'."
    }
    $fullPath = [System.IO.Path]::GetFullPath((Join-Path $root $RelativePath))
    if (-not $fullPath.StartsWith($root + [System.IO.Path]::DirectorySeparatorChar, [System.StringComparison]::Ordinal)) {
        throw "Path escapes the repository: '$RelativePath'."
    }
    return $fullPath
}

function Read-Source {
    param([string]$RelativePath)
    $path = Resolve-RepoPath $RelativePath
    if (-not [System.IO.File]::Exists($path)) { throw "Missing source file: $RelativePath" }
    return [System.IO.File]::ReadAllText($path, $utf8).Replace("`r`n", "`n").Replace("`r", "`n").TrimEnd("`n")
}

function Get-ParsedScript {
    param([string]$Text, [string]$Name)
    $tokens = $null
    $parseErrors = $null
    $ast = [System.Management.Automation.Language.Parser]::ParseInput($Text, [ref]$tokens, [ref]$parseErrors)
    if ($parseErrors.Count -gt 0) {
        throw "PowerShell parse failure in ${Name}: $($parseErrors[0].Message)"
    }
    return $ast
}

function Read-FunctionSource {
    param([string]$RelativePath)
    $text = Read-Source $RelativePath
    $ast = Get-ParsedScript $text $RelativePath
    if ($null -ne $ast.ParamBlock -or $null -ne $ast.BeginBlock -or $null -ne $ast.ProcessBlock -or
        $null -ne $ast.DynamicParamBlock -or
        ($null -ne $ast.PSObject.Properties['CleanBlock'] -and $null -ne $ast.PSObject.Properties['CleanBlock'].Value) -or
        $ast.UsingStatements.Count -gt 0) {
        throw "Source units must contain function declarations only: $RelativePath"
    }
    $statements = @($ast.EndBlock.Statements)
    if ($statements.Count -eq 0 -or @($statements | Where-Object {
        $_ -isnot [System.Management.Automation.Language.FunctionDefinitionAst]
    }).Count -gt 0) {
        throw "Source units must contain function declarations only: $RelativePath"
    }
    return [pscustomobject]@{ Text = $text; Functions = @($statements.Name) }
}

function New-GeneratedHeader {
    param([string[]]$Sources)
    return @(
        "$generatedMarker DO NOT EDIT."
        "# Passkey source version: $version"
        '# Edit the following source files, then run build/build.ps1:'
        @($Sources | ForEach-Object { "#   $_" })
    ) -join "`n"
}

function New-SourceBundle {
    param([string[]]$Sources)
    $names = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::OrdinalIgnoreCase)
    $parts = [System.Collections.Generic.List[string]]::new()
    foreach ($source in $Sources) {
        $unit = Read-FunctionSource $source
        foreach ($name in $unit.Functions) {
            if (-not $names.Add($name)) { throw "Duplicate function '$name' in source list at $source" }
        }
        $parts.Add("# Source: $source`n$($unit.Text)`n# End source: $source")
    }
    return [pscustomobject]@{ Text = $parts -join "`n`n"; Functions = $names }
}

function Add-Artifact {
    param([string]$RelativePath, [string]$Text)
    $null = Resolve-RepoPath $RelativePath
    if ($artifacts.Contains($RelativePath)) { throw "Duplicate generated target: $RelativePath" }
    $normalized = $Text.Replace("`r`n", "`n").Replace("`r", "`n").TrimEnd("`n") + "`n"
    $null = Get-ParsedScript $normalized $RelativePath
    $artifacts.Add($RelativePath, $utf8.GetBytes($normalized))
}

$targetsPath = Resolve-RepoPath 'build/targets.psd1'
if (-not [System.IO.File]::Exists($targetsPath)) { throw 'Missing build/targets.psd1.' }
$targets = Import-PowerShellDataFile $targetsPath
foreach ($key in @('VersionFile', 'ModuleSources', 'Exports', 'ModulePath', 'Scripts')) {
    if (-not $targets.ContainsKey($key)) { throw "Missing build target setting: $key" }
}
if ($targets.VersionFile -ne 'build/VERSION') { throw 'VersionFile must be build/VERSION.' }
$version = (Read-Source $targets.VersionFile).Trim()
if ($version -cnotmatch '^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$') {
    throw 'Version must be exactly three numeric SemVer components, without prefixes or suffixes.'
}
$null = [version]::Parse($version)
$modulePowerShellVersion = '7.6'
if ($targets.ContainsKey('ModulePowerShellVersion')) { $modulePowerShellVersion = [string]$targets.ModulePowerShellVersion }
if ($modulePowerShellVersion -cnotmatch '^[0-9]+\.[0-9]+$' -or [version]$modulePowerShellVersion -lt [version]'7.6') {
    throw 'ModulePowerShellVersion must be a supported major.minor version, at least 7.6.'
}
$modulePath = [string]$targets.ModulePath
$moduleName = Split-Path -Leaf $modulePath
if ($moduleName -cnotmatch '^[A-Za-z][A-Za-z0-9.]*$') { throw "Invalid module name: $moduleName" }
$exports = @($targets.Exports)
if ($exports.Count -eq 0 -or @($exports | Sort-Object -Unique).Count -ne $exports.Count) {
    throw 'Exports must be a nonempty explicit list without duplicates.'
}
foreach ($export in $exports) {
    if ($export -cnotmatch '^[A-Za-z]+-[A-Za-z][A-Za-z0-9]*$') { throw "Invalid exported command name: $export" }
}
# Every canonical source and entrypoint must belong to an explicit target list.
# This catches orphaned units and accidental source omissions before rendering.
$listedSources = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)
$listedEntrypoints = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)
foreach ($source in @($targets.ModuleSources)) { $null = $listedSources.Add([string]$source) }
foreach ($target in @($targets.Scripts)) {
    foreach ($source in @($target.Sources)) { $null = $listedSources.Add([string]$source) }
    $null = $listedEntrypoints.Add([string]$target.EntryPoint)
}
foreach ($sourceRoot in @('powershell/src', 'powershell/entrypoints')) {
    $directory = Resolve-RepoPath $sourceRoot
    if (-not [System.IO.Directory]::Exists($directory)) { throw "Missing canonical source directory: $sourceRoot" }
    $listed = if ($sourceRoot -eq 'powershell/src') { $listedSources } else { $listedEntrypoints }
    foreach ($file in Get-ChildItem -LiteralPath $directory -File -Recurse -Force | Where-Object { $_.Extension -in @('.ps1', '.psm1') }) {
        $relative = [System.IO.Path]::GetRelativePath($root, $file.FullName).Replace('\', '/')
        if (-not $listed.Contains($relative)) { throw "Unlisted source/entrypoint file: $relative" }
    }
}
$artifacts = [ordered]@{}
$moduleSources = @($targets.ModuleSources)
$moduleBundle = New-SourceBundle $moduleSources
foreach ($export in $exports) {
    if (-not $moduleBundle.Functions.Contains($export)) { throw "Exported command is not defined: $export" }
}
$quotedExports = @($exports | ForEach-Object { "'$_'" }) -join ', '
$moduleText = "#Requires -Version $modulePowerShellVersion`n`n$(New-GeneratedHeader $moduleSources)`n`n$($moduleBundle.Text)`n`nExport-ModuleMember -Function @($quotedExports)"
Add-Artifact "$modulePath/$moduleName.psm1" $moduleText
$manifest = @"
$(New-GeneratedHeader $moduleSources)
@{
    RootModule = '$moduleName.psm1'
    ModuleVersion = '$version'
    GUID = 'a78bf2b5-28b6-4f67-b27f-7bfcfe596164'
    Author = 'research-passkeys contributors'
    Description = 'Shared passkey research commands. Importing the module does not invoke authentication flows.'
    PowerShellVersion = '$modulePowerShellVersion'
    FunctionsToExport = @($quotedExports)
    CmdletsToExport = @()
    VariablesToExport = @()
    AliasesToExport = @()
}
"@
Add-Artifact "$modulePath/$moduleName.psd1" $manifest

foreach ($target in @($targets.Scripts)) {
    foreach ($key in @('Path', 'EntryPoint', 'Sources')) {
        if (-not $target.ContainsKey($key)) { throw "Script target lacks $key" }
    }
    $entrypoint = Read-Source $target.EntryPoint
    $marker = '(?m)^# Invoke public command[ \t]*$'
    $matches = [regex]::Matches($entrypoint, $marker)
    if ($matches.Count -ne 1) { throw "Entrypoint must contain exactly one '# Invoke public command' line: $($target.EntryPoint)" }
    $match = $matches[0]
    $preamble = $entrypoint.Substring(0, $match.Index).TrimEnd("`n")
    $invocation = $entrypoint.Substring($match.Index).TrimEnd("`n")
    $preambleAst = Get-ParsedScript $preamble $target.EntryPoint
    if ($null -eq $preambleAst.ParamBlock -or
        @($preambleAst.ParamBlock.Attributes | Where-Object { $_.TypeName.Name -eq 'CmdletBinding' }).Count -ne 1 -or
        $null -eq $preambleAst.ScriptRequirements -or $null -eq $preambleAst.ScriptRequirements.RequiredPSVersion) {
        throw "Entrypoint must retain #Requires, CmdletBinding and a param block: $($target.EntryPoint)"
    }
    if (@($preambleAst.EndBlock.Statements).Count -gt 0 -or $null -ne $preambleAst.BeginBlock -or
        $null -ne $preambleAst.ProcessBlock -or $null -ne $preambleAst.DynamicParamBlock) {
        throw "Entrypoint preamble must contain only help, requirements and parameters: $($target.EntryPoint)"
    }
    if ($null -eq $preambleAst.GetHelpContent()) { throw "Entrypoint lacks valid comment-based help (separate #Requires from the help with a blank line): $($target.EntryPoint)" }
    $invocationAst = Get-ParsedScript $invocation $target.EntryPoint
    if (@($invocationAst.FindAll({ param($node) $node -is [System.Management.Automation.Language.FunctionDefinitionAst] }, $true)).Count -gt 0) {
        throw "Entrypoints may not define helper functions: $($target.EntryPoint)"
    }
    $sources = @($target.Sources)
    $bundle = New-SourceBundle $sources
    $header = New-GeneratedHeader (@($target.EntryPoint) + $sources)
    Add-Artifact $target.Path "$preamble`n`n$header`n`n$($bundle.Text)`n`n$invocation"
}

# Scan the dedicated module directory and all generated markers, including untracked
# files. Previous target inventories catch removed/renamed targets even if edited by hand.
$observed = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)
if ($targets.ContainsKey('GeneratedScriptDirectories')) {
    foreach ($directory in @($targets.GeneratedScriptDirectories)) {
        $fullPath = Resolve-RepoPath $directory
        if ([System.IO.Directory]::Exists($fullPath)) {
            foreach ($file in Get-ChildItem -LiteralPath $fullPath -File -Force -Filter '*.ps1') {
                $null = $observed.Add([System.IO.Path]::GetRelativePath($root, $file.FullName).Replace('\', '/'))
            }
        }
    }
}
$moduleDirectory = Resolve-RepoPath $modulePath
if ([System.IO.Directory]::Exists($moduleDirectory)) {
    foreach ($file in Get-ChildItem -LiteralPath $moduleDirectory -File -Recurse -Force) {
        $relative = [System.IO.Path]::GetRelativePath($root, $file.FullName).Replace('\', '/')
        $null = $observed.Add($relative)
    }
}
foreach ($file in Get-ChildItem -LiteralPath $root -File -Recurse -Force -Include '*.ps1', '*.psm1', '*.psd1' | Where-Object {
    $_.FullName -notlike "$root$([System.IO.Path]::DirectorySeparatorChar).git$([System.IO.Path]::DirectorySeparatorChar)*"
}) {
    if ([System.IO.File]::ReadAllText($file.FullName, $utf8).Contains($generatedMarker)) {
        # The build script itself contains the marker as a quoted string, not a generated header.
        if ([regex]::IsMatch([System.IO.File]::ReadAllText($file.FullName, $utf8), '(?m)^' + [regex]::Escape($generatedMarker))) {
            $null = $observed.Add([System.IO.Path]::GetRelativePath($root, $file.FullName).Replace('\', '/'))
        }
    }
}
$git = Get-Command git -ErrorAction SilentlyContinue
if ($null -ne $git -and (Test-Path -LiteralPath (Join-Path $root '.git'))) {
    # An unborn HEAD is also expected in a newly initialized source repository.
    # Probe it without promoting its known absence to a strict-native error.
    $nativePreference = $PSNativeCommandUseErrorActionPreference
    try {
        $PSNativeCommandUseErrorActionPreference = $false
        $previousHead = @(& git -C $root rev-parse --verify --quiet HEAD 2>$null)
        $headExitCode = $LASTEXITCODE
    } finally {
        $PSNativeCommandUseErrorActionPreference = $nativePreference
    }
    if ($headExitCode -eq 1) {
        $null = & git -C $root rev-parse --git-dir 2>$null
        if ($LASTEXITCODE -ne 0) { throw 'Unable to inspect the Git source repository.' }
    } elseif ($headExitCode -eq 0 -and $previousHead.Count -eq 1) {
        # Absence is expected on first introduction; ls-tree succeeds without leaving
        # a failing native exit code for GitHub's pwsh wrapper to propagate.
        $previousPaths = @(& git -C $root ls-tree --name-only HEAD -- 'build/targets.psd1' 2>$null)
        if ($LASTEXITCODE -ne 0) { throw 'Unable to inspect the previous target inventory.' }
        if ($previousPaths -contains 'build/targets.psd1') {
            $previousText = @(& git -C $root show 'HEAD:build/targets.psd1' 2>$null)
            if ($LASTEXITCODE -ne 0) { throw 'Unable to read the previous target inventory.' }
            $previousAst = Get-ParsedScript ($previousText -join "`n") 'HEAD:build/targets.psd1'
            $hashAst = @($previousAst.EndBlock.Statements)
            if ($hashAst.Count -ne 1 -or $hashAst[0] -isnot [System.Management.Automation.Language.PipelineAst] -or
                $hashAst[0].PipelineElements.Count -ne 1 -or
                $hashAst[0].PipelineElements[0] -isnot [System.Management.Automation.Language.CommandExpressionAst] -or
                $hashAst[0].PipelineElements[0].Expression -isnot [System.Management.Automation.Language.HashtableAst]) {
                throw 'Previous target inventory is not a static PowerShell data file.'
            }
            $previous = $hashAst[0].PipelineElements[0].Expression.SafeGetValue()
            if ($previous -is [System.Collections.IDictionary]) {
                foreach ($oldTarget in @($previous.Scripts)) {
                    if ([System.IO.File]::Exists((Resolve-RepoPath $oldTarget.Path))) { $null = $observed.Add([string]$oldTarget.Path) }
                }
                $oldModule = [string]$previous.ModulePath
                $oldName = Split-Path -Leaf $oldModule
                foreach ($oldPath in @("$oldModule/$oldName.psm1", "$oldModule/$oldName.psd1")) {
                    if ([System.IO.File]::Exists((Resolve-RepoPath $oldPath))) { $null = $observed.Add($oldPath) }
                }
            }
        }
    } else {
        throw 'Unable to inspect the previous target inventory.'
    }
}
$extra = @($observed | Where-Object { -not $artifacts.Contains($_) } | Sort-Object)
if ($extra.Count -gt 0) { throw "Unexpected generated files; remove them deliberately: $($extra -join ', ')" }

if ($Check) {
    $failures = [System.Collections.Generic.List[string]]::new()
    foreach ($entry in $artifacts.GetEnumerator()) {
        $path = Resolve-RepoPath $entry.Key
        if (-not [System.IO.File]::Exists($path)) { $failures.Add("Missing: $($entry.Key)"); continue }
        $actual = [System.IO.File]::ReadAllBytes($path)
        if (-not [System.Linq.Enumerable]::SequenceEqual[byte]($actual, $entry.Value)) {
            $failures.Add("Stale or edited: $($entry.Key)")
        }
    }
    if ($failures.Count -gt 0) { throw "Generated artifact drift. Run build/build.ps1 and include its output in the same change.`n$($failures -join "`n")" }
    Write-Host "Generated artifact check passed: $($artifacts.Count) files, version $version."
} else {
    foreach ($entry in $artifacts.GetEnumerator()) {
        $path = Resolve-RepoPath $entry.Key
        $null = [System.IO.Directory]::CreateDirectory([System.IO.Path]::GetDirectoryName($path))
        [System.IO.File]::WriteAllBytes($path, $entry.Value)
    }
    Write-Host "Built $($artifacts.Count) files, version $version."
}
