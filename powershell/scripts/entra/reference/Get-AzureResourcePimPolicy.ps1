function ConvertFrom-AzurePimEligibilityItem {
    param([Parameter(Mandatory)][hashtable]$Item)
    $props = if ($Item.ContainsKey('properties') -and $Item['properties'] -is [System.Collections.IDictionary]) { $Item['properties'] } else { @{} }
