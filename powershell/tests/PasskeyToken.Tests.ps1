    function New-SyntheticJwt {
        param(
            [string]$TenantId = '33333333-3333-3333-3333-333333333333',
            [string]$Upn = 'user@example.test',
            [string]$Scope = 'User.Read'
        )
        $claims = @{
            aud = 'https://graph.microsoft.com'
            tid = $TenantId
            upn = $Upn
            scp = $Scope
            amr = @('fido', 'mfa')
            exp = [DateTimeOffset]::UtcNow.AddMinutes(30).ToUnixTimeSeconds()
        }
        $encoded = ConvertTo-Base64Url ([System.Text.Encoding]::UTF8.GetBytes(($claims | ConvertTo-Json -Compress)))
        return "e30.$encoded.c2ln"
    }
}

Describe 'Generated token scripts compatibility and structure' {
    It 'keeps both generated token scripts self-contained and matching source version' {
        foreach ($name in @('Get-EntraPasskeyAccessToken', 'Get-EntraPasskeyAccessTokenViaDeviceCode')) {
            $path = Join-Path $RepositoryRoot "powershell/scripts/entra/reference/$name.ps1"
            Test-Path -LiteralPath $path | Should -BeTrue
            $text = Get-Content -LiteralPath $path -Raw
            $text | Should -Match '^#Requires -Version 7\.6'
            $text | Should -Match 'Generated by build/build\.ps1'
            $text | Should -Not -Match 'Import-Module|Invoke-Expression'
            $tokens = $null; $errors = $null
            $null = [System.Management.Automation.Language.Parser]::ParseFile($path, [ref]$tokens, [ref]$errors)
            $errors.Count | Should -Be 0
        }
    }

    It 'keeps entrypoints bounded to param block and single command invocation' {
        foreach ($name in @('Get-EntraPasskeyAccessToken', 'Get-EntraPasskeyAccessTokenViaDeviceCode')) {
            $path = Join-Path $RepositoryRoot "powershell/entrypoints/$name.ps1"
            $text = Get-Content -LiteralPath $path -Raw
            $tail = ($text -split '# Invoke public command', 2)[1].Trim()
            $tail | Should -BeExactly "$name @PSBoundParameters"
        }
    }
}

Describe 'Passkey token acquisition via PKCE' {
    BeforeEach {
        $script:syntheticSession = [Microsoft.PowerShell.Commands.WebRequestSession]::new()
        $script:capturedPkceState = $null
        $script:capturedVerifier = $null
        $script:capturedRedirect = $null
        $script:jwt = New-SyntheticJwt

        Mock Invoke-EntraPasskeyLogin {
            [pscustomobject]@{
                Success                  = $true
                UserPrincipalName        = 'user@example.test'
                AuthenticationMethod     = 'Legacy software FIDO2 assertion'
                SignatureMethod          = 'Local Private Key'
                KeyVaultName             = $null
                AuthenticationSession    = $script:syntheticSession
                UserPresenceVerified     = $false
                UserVerificationVerified = $false
            }
        }
    }

    It 'rejects invalid ClientId or TenantId before network or passkey login' {
        { Get-EntraPasskeyAccessToken -KeyFilePath 'dummy.json' -ClientId 'not-a-guid' } | Should -Throw '*ClientId*'
        { Get-EntraPasskeyAccessToken -KeyFilePath 'dummy.json' -TenantId 'not-a-guid' } | Should -Throw '*TenantId*'
        Should -Invoke Invoke-EntraPasskeyLogin -Times 0 -Exactly
    }

    It 'acquires SecureString tokens by default and handles CmsiInterrupt + localhost redirect' {
        Mock Invoke-EntraTokenHttpRequest {
            if ($Uri -like '*/.well-known/openid-configuration') {
                return [pscustomobject]@{ StatusCode = 200; Location = $null; Content = '{"issuer":"https://login.microsoftonline.com/33333333-3333-3333-3333-333333333333/v2.0"}' }
            }
            if ($Uri -like '*/oauth2/v2.0/authorize*') {
                $q = [System.Web.HttpUtility]::ParseQueryString(([uri]$Uri).Query)
                $script:capturedPkceState = $q['state']
                return [pscustomobject]@{
                    StatusCode = 200
                    Location   = $null
                    Content    = '$Config={"pgid":"CmsiInterrupt","urlPost":"/appverify","canary":"c1","sFT":"ft1","correlationId":"corr1","sCtx":"ctx1"};'
                }
            }
            if ($Uri -eq 'https://login.microsoftonline.com/appverify') {
                return [pscustomobject]@{
                    StatusCode = 302
                    Location   = "http://localhost/?code=synthetic-auth-code&state=$($script:capturedPkceState)"
                    Content    = ''
                }
            }
            if ($Uri -eq 'https://login.microsoftonline.com/33333333-3333-3333-3333-333333333333/oauth2/v2.0/token') {
                $form = [System.Web.HttpUtility]::ParseQueryString($Body)
                if ($form['code'] -ne 'synthetic-auth-code' -or $form['redirect_uri'] -ne 'http://localhost') {
                    throw 'Unexpected token request payload.'
                }
                return [pscustomobject]@{
                    StatusCode = 200
                    Location   = $null
                    Content    = (@{ token_type = 'Bearer'; scope = 'User.Read'; expires_in = 3600; access_token = $script:jwt; refresh_token = 'synthetic-refresh' } | ConvertTo-Json -Compress)
                }
            }
            throw "Unexpected URI: $Uri"
        }

        $res = Get-EntraPasskeyAccessToken -KeyFilePath 'dummy.json' -RedirectUri 'http://localhost' -IncludeRefreshToken
        $res.Success | Should -BeTrue
        $res.AuthFlow | Should -BeExactly 'PasskeyAuthorizationCodePKCE'
        $res.TenantId | Should -BeExactly '33333333-3333-3333-3333-333333333333'
        $res.AccessToken | Should -BeOfType ([System.Security.SecureString])
        $res.RefreshToken | Should -BeOfType ([System.Security.SecureString])
        [System.Net.NetworkCredential]::new('', $res.AccessToken).Password | Should -BeExactly $script:jwt
    }

    It 'supports -RawToken and -Json -AsPlainText output modes' {
        Mock Invoke-EntraTokenHttpRequest {
            if ($Uri -like '*/oauth2/v2.0/authorize*') {
                $q = [System.Web.HttpUtility]::ParseQueryString(([uri]$Uri).Query)
                return [pscustomobject]@{
                    StatusCode = 302
                    Location   = "https://login.microsoftonline.com/common/oauth2/nativeclient?code=code-1&state=$($q['state'])"
                    Content    = ''
                }
            }
            if ($Uri -like '*/oauth2/v2.0/token') {
                return [pscustomobject]@{
                    StatusCode = 200
                    Location   = $null
                    Content    = (@{ token_type = 'Bearer'; scope = 'User.Read'; expires_in = 3600; access_token = $script:jwt } | ConvertTo-Json -Compress)
                }
            }
            throw "Unexpected URI: $Uri"
        }

        $raw = Get-EntraPasskeyAccessToken -KeyFilePath 'dummy.json' -TenantId '33333333-3333-3333-3333-333333333333' -RawToken
        $raw | Should -BeOfType ([string])
        $raw | Should -BeExactly $script:jwt

        $jsonOut = Get-EntraPasskeyAccessToken -KeyFilePath 'dummy.json' -TenantId '33333333-3333-3333-3333-333333333333' -Json -AsPlainText | ConvertFrom-Json
        $jsonOut.success | Should -BeTrue
        $jsonOut.accessToken | Should -BeExactly $script:jwt
    }

    It 'refuses Consent pages during PKCE authorization' {
        Mock Invoke-EntraTokenHttpRequest {
            [pscustomobject]@{ StatusCode = 200; Location = $null; Content = '$Config={"pgid":"Consent"};' }
        }
        { Get-EntraPasskeyAccessToken -KeyFilePath 'dummy.json' -TenantId '33333333-3333-3333-3333-333333333333' } | Should -Throw '*Consent*'
    }
}

Describe 'Passkey token acquisition via Device Code Flow' {
    BeforeEach {
        $script:syntheticSession = [Microsoft.PowerShell.Commands.WebRequestSession]::new()
        $script:jwt = New-SyntheticJwt
        $script:pollCount = 0

        Mock Invoke-EntraPasskeyLogin {
            [pscustomobject]@{
                Success                  = $true
                UserPrincipalName        = 'user@example.test'
                AuthenticationMethod     = 'Legacy software FIDO2 assertion'
                SignatureMethod          = 'Local Private Key'
                KeyVaultName             = $null
                AuthenticationSession    = $script:syntheticSession
                UserPresenceVerified     = $false
                UserVerificationVerified = $false
            }
        }
        Mock Start-Sleep {}
    }

    It 'initiates device code, completes deviceauth with passkey session, polls pending, and returns token' {
        Mock Invoke-EntraTokenHttpRequest {
            if ($Uri -like '*/oauth2/v2.0/devicecode') {
                return [pscustomobject]@{
                    StatusCode = 200; Location = $null
                    Content    = '{"user_code":"ABCD12345","device_code":"dev-code-1","verification_uri":"https://login.microsoft.com/device","expires_in":900,"interval":1}'
                }
            }
            if ($Uri -eq 'https://login.microsoft.com/device') {
                return [pscustomobject]@{ StatusCode = 302; Location = 'https://login.microsoftonline.com/common/oauth2/deviceauth'; Content = '' }
            }
            if ($Uri -eq 'https://login.microsoftonline.com/common/oauth2/deviceauth' -and $Method -eq 'GET') {
                return [pscustomobject]@{ StatusCode = 200; Location = $null; Content = '$Config={"pgid":"ConvergedRemoteConnect","urlPost":"https://login.microsoftonline.com/common/oauth2/deviceauth","canary":"can1","sFT":""};' }
            }
            if ($Uri -eq 'https://login.microsoftonline.com/common/oauth2/deviceauth' -and $Method -eq 'POST') {
                $form = [System.Web.HttpUtility]::ParseQueryString($Body)
                if ($form['otc'] -ne 'ABCD12345') { throw 'Wrong otc' }
                return [pscustomobject]@{ StatusCode = 200; Location = $null; Content = '$Config={"pgid":"ConvergedSignIn","urlLogin":"https://login.microsoftonline.com/33333333-3333-3333-3333-333333333333/reprocess?ctx=1","arrSessions":[{"id":"sess1"}]};' }
            }
            if ($Uri -like '*/reprocess*') {
                return [pscustomobject]@{ StatusCode = 200; Location = $null; Content = '$Config={"pgid":"CmsiInterrupt","urlPost":"/appverify","canary":"can2","sFT":"ft2","correlationId":"corr2","sCtx":"ctx2"};' }
            }
            if ($Uri -eq 'https://login.microsoftonline.com/appverify') {
                return [pscustomobject]@{ StatusCode = 200; Location = $null; Content = '$Config={"pgid":"ConvergedMessage","stsErrorCode":0,"sRemoteConnectAppName":"Microsoft Azure CLI"};' }
            }
            if ($Uri -like '*/oauth2/v2.0/token') {
                $script:pollCount++
                if ($script:pollCount -eq 1) {
                    return [pscustomobject]@{ StatusCode = 400; Location = $null; Content = '{"error":"authorization_pending"}' }
                }
                return [pscustomobject]@{
                    StatusCode = 200; Location = $null
                    Content    = (@{ token_type = 'Bearer'; scope = 'User.Read'; expires_in = 3600; access_token = $script:jwt } | ConvertTo-Json -Compress)
                }
            }
            throw "Unexpected URI: $Uri ($Method)"
        }

        $res = Get-EntraPasskeyAccessTokenViaDeviceCode -KeyFilePath 'dummy.json' -TenantId '33333333-3333-3333-3333-333333333333' -AsPlainText
        $res.Success | Should -BeTrue
        $res.AuthFlow | Should -BeExactly 'PasskeyDeviceCode'
        $res.UserCode | Should -BeExactly 'ABCD12345'
        $res.AccessToken | Should -BeExactly $script:jwt
        $script:pollCount | Should -Be 2
    }

    It 'completes an externally supplied -UserCode without calling devicecode or token polling' {
        Mock Invoke-EntraTokenHttpRequest {
            if ($Uri -like '*/oauth2/v2.0/devicecode' -or $Uri -like '*/oauth2/v2.0/token') {
                throw "Should not call $Uri when -UserCode is supplied."
            }
            if ($Uri -eq 'https://login.microsoftonline.com/common/oauth2/deviceauth' -and $Method -eq 'GET') {
                return [pscustomobject]@{ StatusCode = 200; Location = $null; Content = '$Config={"pgid":"ConvergedRemoteConnect","urlPost":"https://login.microsoftonline.com/common/oauth2/deviceauth","canary":"can1","sFT":""};' }
            }
            if ($Uri -eq 'https://login.microsoftonline.com/common/oauth2/deviceauth' -and $Method -eq 'POST') {
                return [pscustomobject]@{ StatusCode = 200; Location = $null; Content = '$Config={"pgid":"ConvergedMessage","stsErrorCode":0,"sRemoteConnectAppName":"External CLI"};' }
            }
            throw "Unexpected URI: $Uri ($Method)"
        }

        $res = Get-EntraPasskeyAccessTokenViaDeviceCode -KeyFilePath 'dummy.json' -UserCode 'EXT123456'
        $res.Success | Should -BeTrue
        $res.AuthFlow | Should -BeExactly 'PasskeyDeviceCodeExternalUserCode'
        $res.UserCode | Should -BeExactly 'EXT123456'
        $res.AppName | Should -BeExactly 'External CLI'
    }

    It 'fails clearly when an invalid device user code is rejected by Entra' {
        Mock Invoke-EntraTokenHttpRequest {
            if ($Uri -eq 'https://login.microsoftonline.com/common/oauth2/deviceauth' -and $Method -eq 'GET') {
                return [pscustomobject]@{ StatusCode = 200; Location = $null; Content = '$Config={"pgid":"ConvergedRemoteConnect","urlPost":"https://login.microsoftonline.com/common/oauth2/deviceauth","canary":"can1","sFT":""};' }
            }
            if ($Uri -eq 'https://login.microsoftonline.com/common/oauth2/deviceauth' -and $Method -eq 'POST') {
                return [pscustomobject]@{ StatusCode = 200; Location = $null; Content = '$Config={"pgid":"ConvergedRemoteConnect","stsErrorCode":90019};' }
            }
        }
        { Get-EntraPasskeyAccessTokenViaDeviceCode -KeyFilePath 'dummy.json' -UserCode 'BADCODE99' } | Should -Throw '*rejected*'
    }
